import type { ConversionClient } from '../services/ConversionService';
import type { UseConversionFlowApi } from './conversion_flow_contract';
export type { UseConversionFlowApi } from './conversion_flow_contract';
import { useConversionState } from './useConversionState';
import { useConversionSnapshots } from './useConversionSnapshots';
import { useHttpRuntimeHealth } from './useHttpRuntimeHealth';
import { useConversionHistory } from './useConversionHistory';
import { useConversionRunSession } from './useConversionRunSession';
import { useConversionQueue } from './useConversionQueue';
import { useConversionResume } from './useConversionResume';
import { useConversionControls } from './useConversionControls';
import { useConversionIntents } from './useConversionIntents';

export function useConversionFlow(client?: ConversionClient): UseConversionFlowApi {
  const {
    stateRef,
    saveStateWithQueue,
    fileNameRef,
    streamStatusRef,
    fallbackPollAbortRef,
    restartGraceRef,
    healthFailureCountRef,
    pollFailureCountRef,
    setApiAvailable,
    setHealthStatus,
    isRestartGraceActive,
    adaptiveTolerancesRef,
    state,
    lastSnapshotAtRef,
    api,
    seenEventsRef,
    dispatch,
    entryFactoryRef,
    setCachedJobs,
    apiAvailable,
    startTimeRef,
    setCachedJobsLoading,
    setRecentJobs,
    abortRef,
    t,
    queueActiveRef,
    queueGenerationRef,
    queuePausedRef,
    jobQueueRef,
    syncQueueSnapshot,
    processedCountRef,
    skipModeRef,
    setQueuePaused,
    setSavedBatch,
    beginRestartGrace,
    cachedJobs,
    cachedJobsLoading,
    recentJobs,
    healthStatus,
    queueSnapshot,
    queuePaused,
    savedBatch,
  } = useConversionState({ client });
  const {
    markApiOnline,
    markApiOffline,
    appendSnapshotEvents,
    applySnapshotMeta,
    shouldMarkOffline,
    waitForBackendReady,
    onStreamStatus,
    saveSnapshotToCache,
    clearCancelledJob,
  } = useConversionSnapshots({
    stateRef,
    saveStateWithQueue,
    fileNameRef,
    streamStatusRef,
    fallbackPollAbortRef,
    restartGraceRef,
    healthFailureCountRef,
    pollFailureCountRef,
    setApiAvailable,
    setHealthStatus,
    isRestartGraceActive,
    adaptiveTolerancesRef,
    state,
    lastSnapshotAtRef,
    api,
    seenEventsRef,
    dispatch,
    entryFactoryRef,
    setCachedJobs,
    apiAvailable,
  });
  useHttpRuntimeHealth({
    client,
    api,
    setApiAvailable,
    state,
    adaptiveTolerancesRef,
    lastSnapshotAtRef,
    markApiOnline,
    healthFailureCountRef,
    markApiOffline,
    streamStatusRef,
    fallbackPollAbortRef,
    pollFailureCountRef,
    appendSnapshotEvents,
    startTimeRef,
    applySnapshotMeta,
    dispatch,
  });
  useConversionHistory({
    setCachedJobsLoading,
    setCachedJobs,
    shouldMarkOffline,
    markApiOffline,
    apiAvailable,
    api,
    markApiOnline,
    setRecentJobs,
  });
  const { runConversion, resetLogAndCounters, reset } = useConversionRunSession({
    queueGenerationRef,
    jobQueueRef,
    queueActiveRef,
    skipModeRef,
    syncQueueSnapshot,
    setQueuePaused,
    entryFactoryRef,
    seenEventsRef,
    abortRef,
    lastSnapshotAtRef,
    startTimeRef,
    dispatch,
    apiAvailable,
    t,
    waitForBackendReady,
    fileNameRef,
    api,
    markApiOnline,
    appendSnapshotEvents,
    applySnapshotMeta,
    markApiOffline,
    onStreamStatus,
    saveSnapshotToCache,
    clearCancelledJob,
    state,
  });
  const { drainQueue, submit, enqueue } = useConversionQueue({
    queueGenerationRef,
    queueActiveRef,
    queuePausedRef,
    jobQueueRef,
    syncQueueSnapshot,
    processedCountRef,
    runConversion,
    skipModeRef,
    dispatch,
    setQueuePaused,
    entryFactoryRef,
    t,
    state,
    saveStateWithQueue,
    fileNameRef,
    setSavedBatch,
  });
  const { resume } = useConversionResume({
    abortRef,
    resetLogAndCounters,
    lastSnapshotAtRef,
    dispatch,
    entryFactoryRef,
    t,
    jobQueueRef,
    processedCountRef,
    setQueuePaused,
    drainQueue,
    fileNameRef,
    seenEventsRef,
    syncQueueSnapshot,
    startTimeRef,
    apiAvailable,
    waitForBackendReady,
    api,
    markApiOnline,
    setCachedJobs,
    markApiOffline,
    appendSnapshotEvents,
    applySnapshotMeta,
    onStreamStatus,
    saveSnapshotToCache,
    clearCancelledJob,
    state,
  });
  const {
    cancel,
    skipCurrent,
    cancelJobById,
    removeCachedJob,
    uploadFile,
    resumeQueue,
    clearQueue,
    reorderQueue,
    restartBackend,
  } = useConversionControls({
    abortRef,
    state,
    startTimeRef,
    entryFactoryRef,
    t,
    dispatch,
    clearCancelledJob,
    jobQueueRef,
    queueActiveRef,
    setQueuePaused,
    processedCountRef,
    api,
    skipModeRef,
    drainQueue,
    apiAvailable,
    setCachedJobs,
    markApiOnline,
    markApiOffline,
    syncQueueSnapshot,
    beginRestartGrace,
    reset,
    setRecentJobs,
  });
  return useConversionIntents({
    state,
    setSavedBatch,
    submit,
    enqueue,
    resume,
    reset,
    cancel,
    skipCurrent,
    cancelJobById,
    removeCachedJob,
    uploadFile,
    cachedJobs,
    cachedJobsLoading,
    recentJobs,
    apiAvailable,
    healthStatus,
    markApiOnline,
    queueSnapshot,
    queuePaused,
    resumeQueue,
    clearQueue,
    reorderQueue,
    restartBackend,
    savedBatch,
  });
}
