#!/usr/bin/env bash
set -u

# Report the final Rust migration gate without mutating the repository.

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

failures=0
blockers=()

pass() { printf 'PASS %s\n' "$1"; }
fail() {
  printf 'BLOCKED %s\n' "$1"
  blockers+=("$1")
  failures=$((failures + 1))
}

printf 'Rust migration gate\n===================\n'

if [[ -f Cargo.toml ]]; then
  pass "Rust workspace manifest exists"
  workspace_members="$(sed -n '/^members = \[/,/^\]/p' Cargo.toml | sed -n 's/.*"\([^"]*\)".*/\1/p')"
  while IFS= read -r member; do
    [[ -z "$member" ]] && continue
    if [[ -f "$member/Cargo.toml" ]]; then
      pass "Rust workspace member: $member"
    else
      fail "Missing Cargo manifest for workspace member: $member"
    fi
  done <<< "$workspace_members"
else
  fail "Missing Rust workspace manifest: Cargo.toml"
fi

for entrypoint in \
  crates/converter-cli/src/main.rs \
  crates/converter-server/src/main.rs; do
  if [[ -f "$entrypoint" ]]; then
    pass "Production Rust entrypoint exists: $entrypoint"
  else
    fail "Missing production Rust entrypoint: $entrypoint"
  fi
done

if [[ -x scripts/guard_no_python_production.sh ]]; then
  pass "No-Python production guard is executable"
else
  fail "No-Python production guard missing or not executable: scripts/guard_no_python_production.sh"
fi

# The browser WASM is generated by the Rails gateway build; nothing generated is committed.
if [[ -f crates/converter-wasm/Cargo.toml ]]; then
  pass "WASM crate manifest exists: crates/converter-wasm/Cargo.toml"
else
  fail "Missing WASM crate manifest: crates/converter-wasm/Cargo.toml"
fi
if [[ -x ruby_app/rails_gateway/bin/build-runtime-wasm ]]; then
  pass "Gateway WASM build script exists: ruby_app/rails_gateway/bin/build-runtime-wasm"
else
  fail "Missing gateway WASM build script: ruby_app/rails_gateway/bin/build-runtime-wasm"
fi
if [[ -x ruby_app/rails_gateway/bin/assemble-runtime ]]; then
  pass "Gateway runtime assembly script exists: ruby_app/rails_gateway/bin/assemble-runtime"
else
  fail "Missing gateway runtime assembly script: ruby_app/rails_gateway/bin/assemble-runtime"
fi

artifact_found=0
for artifact in \
  target/release/converter-cli \
  target/release/converter-server; do
  if [[ -e "$artifact" ]]; then
    pass "Generated production artifact exists: $artifact"
    artifact_found=1
  fi
done
if (( artifact_found == 0 )); then
  fail "No generated Rust production artifact found (expected target/release/)"
fi

if [[ -d target ]]; then
  pass "Rust build directory exists: target/"
else
  fail "Rust build artifacts have not been generated: target/"
fi

if (( failures == 0 )); then
  printf '\nRESULT PASS\n'
  exit 0
fi

printf '\nRESULT BLOCKED (%d)\n' "$failures"
printf 'Remaining blockers:\n'
for blocker in "${blockers[@]}"; do
  printf -- '- %s\n' "$blocker"
done
exit 1
