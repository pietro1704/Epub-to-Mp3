# frozen_string_literal: true

require 'minitest/autorun'
require 'tmpdir'
require 'fileutils'
require 'open3'
require 'yaml'
require 'shellwords'
require 'rubygems/package'

class MinitestBootstrapTest < Minitest::Test
  WORKFLOWS = %w[native-hook-safety.yml ci.yml ruby-rust-integration.yml].freeze

  def test_real_gem_install_preserves_existing_toolchain_launcher
    Dir.mktmpdir('minitest bootstrap ') do |root|
      FileUtils.mkdir_p(File.join(root, 'bin'))
      File.write(File.join(root, 'bin/minitest'), "#!/usr/bin/env ruby\nputs 'fixture'\n")
      spec = Gem::Specification.new do |gem|
        gem.name = 'minitest'
        gem.version = '6.0.6'
        gem.summary = 'Offline bootstrap fixture'
        gem.authors = ['Fixture']
        gem.files = ['bin/minitest']
        gem.executables = ['minitest']
      end
      artifact = Dir.chdir(root) { Gem::Package.build(spec, true) }
      toolchain = File.join(root, 'toolchain-bin')
      FileUtils.mkdir_p(toolchain)
      launcher = File.join(toolchain, 'minitest')
      original = "#!/usr/bin/env ruby\n#\n# This file was generated by RubyGems.\nGem.activate_and_load_bin_path('old-minitest', 'minitest', '1')\n"
      File.write(launcher, original)
      environment = { 'GEM_HOME' => File.join(root, 'gems'), 'GEM_PATH' => '', 'RUNNER_TEMP' => root }
      commands = WORKFLOWS.map do |filename|
        workflow = YAML.load_file(File.expand_path("../.github/workflows/#{filename}", __dir__))
        workflow.fetch('jobs').values.flat_map { |job| job.fetch('steps', []) }
          .filter_map { |step| step['run'] }.find { |run| run.include?('gem install minitest') }
      end
      commands.each do |command|
        refute_nil command
        assert_includes command, '--bindir "$RUNNER_TEMP/minitest-bin"'
        # Keep the workflow's actual installer options, using an offline package
        # and an isolated gem home instead of the runner's global installation.
        local = command.sub('mise exec -- ', '').sub('gem install minitest',
          "#{Shellwords.escape(RbConfig.ruby)} -S gem install --local #{Shellwords.escape(File.join(root, artifact))}")
        out, err, status = Open3.capture3(environment, 'bash', '-euc', local)
        assert status.success?, out + err
        assert_equal original, File.read(launcher)
        assert File.file?(File.join(root, 'minitest-bin/minitest'))
      end
      # The same fixture reproduces the original collision when directed to
      # the existing toolchain executable directory.
      _, err, status = Open3.capture3(environment, RbConfig.ruby, '-S', 'gem', 'install',
        '--local', File.join(root, artifact), '--no-document', '--bindir', toolchain)
      refute status.success?
      assert_includes err, 'conflicts with'
      assert_equal original, File.read(launcher)
    end
  end
end
